const dictionaries: Record<Lang, Record<TranslationKey, string>> = { en, bn };

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
  /** Formats a number with the active language's digits. */
  num: (value: number) => string;
  money: (value: number) => string;
  date: (value?: string | Date | null) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    try {
      const stored = window.localStorage.getItem(LANG_KEY);
      if (stored === "en" || stored === "bn") setLangState(stored);
    } catch {
      // Storage unavailable; keep the default.
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      window.localStorage.setItem(LANG_KEY, next);
    } catch {
      // Storage unavailable; the choice lasts for this page view only.
    }
  }, []);

  const value = useMemo<I18nValue>(() => {
    const locale = lang === "bn" ? "bn-BD" : "en-US";
    const num = (n: number) => n.toLocaleString(locale);
    return {
      lang,
      setLang,
      num,
      money: (n: number) => `৳${num(n)}`,
      date: (input) =>
        input
          ? new Date(input).toLocaleDateString(lang === "bn" ? "bn-BD" : "en-GB", {
              day: "numeric",
              month: "short",
              year: "numeric",
            })
          : "—",
      t: (key, vars) => {
        let text = dictionaries[lang][key] ?? en[key] ?? key;
        if (vars) {
          for (const [name, v] of Object.entries(vars)) {
            text = text.replace(`{${name}}`, typeof v === "number" ? num(v) : v);
          }
        }
        return text;
      },
    };
  }, [lang, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside LanguageProvider");
  return ctx;
}
